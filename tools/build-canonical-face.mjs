// Converts MediaPipe's canonical_face_model.obj (Apache-2.0, google-ai-edge/mediapipe,
// mediapipe/modules/face_geometry/data) into a compact TypeScript module.
//
// The OBJ's `v` order equals the Face Landmarker landmark index order (v1 = landmark 0),
// units are centimetres, +X = subject's left, +Y = up, +Z = out of the face toward the camera.
//
// Usage: node tools/build-canonical-face.mjs

import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const src = join(root, 'tools', 'data', 'canonical_face_model.obj');
const out = join(root, 'src', 'tracking', 'canonical-face-data.ts');

const text = await readFile(src, 'utf8');
const positions = [];
const triangles = [];
for (const line of text.split(/\r?\n/)) {
  const parts = line.trim().split(/\s+/);
  if (parts[0] === 'v') positions.push(...parts.slice(1, 4).map(Number));
  else if (parts[0] === 'f') {
    if (parts.length !== 4) throw new Error(`Non-triangle face: ${line}`);
    // "a/ta b/tb c/tc" -> vertex index (1-based) before the slash
    triangles.push(...parts.slice(1).map((p) => Number(p.split('/')[0]) - 1));
  }
}
if (positions.length !== 468 * 3) throw new Error(`Expected 468 vertices, got ${positions.length / 3}`);

const fmt = (arr, perLine, digits) => {
  const lines = [];
  for (let i = 0; i < arr.length; i += perLine) {
    lines.push('  ' + arr.slice(i, i + perLine).map((n) => (digits == null ? String(n) : n.toFixed(digits))).join(', ') + ',');
  }
  return lines.join('\n');
};

const ts = `// AUTO-GENERATED by tools/build-canonical-face.mjs — do not edit by hand.
// Source: MediaPipe canonical_face_model.obj, Copyright The MediaPipe Authors, Apache License 2.0.
// Units: centimetres. Axes: +X subject's left, +Y up, +Z out of the face (toward camera).
// Vertex i corresponds to Face Landmarker landmark index i.

export const CANONICAL_VERTEX_COUNT = ${positions.length / 3};

/** xyz triplets, length ${positions.length}. */
export const CANONICAL_POSITIONS = new Float32Array([
${fmt(positions, 6, 6)}
]);

/** Triangle vertex indices (${triangles.length / 3} triangles). */
export const CANONICAL_TRIANGLES = new Uint16Array([
${fmt(triangles, 18)}
]);
`;
await mkdir(dirname(out), { recursive: true });
await writeFile(out, ts);
console.log(`✓ wrote ${out} (${positions.length / 3} vertices, ${triangles.length / 3} triangles)`);
